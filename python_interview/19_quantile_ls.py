"""进阶：分位数多空 — IC 之外看「因子大的一组是否真赚」。

运行：python 19_quantile_ls.py

# 人话
按当天因子从大到小切成 5 组（五分位）。做多最高组、做空最低组。
看各组下一期平均收益：若 Q5 > Q4 > … > Q1，才像真因子。中间乱、两头尖，可能是非线性或噪声。

# 目的
IC 是当天横着算的一个相关（因子 vs 下期收益，见 12），20 只票收成一个 ρ。
相关最吃离群点：两只票因子特别大/特别小、收益也特别猛，整根线会被它们拽歪。
分层看的是「因子大的那一组平均赚不赚」，不把全部收成一个数。

# 「会被两只极端票拉动」举例

某天 5 只：

    股票     因子     下期收益
    A       +3.0     +20%      因子极大，也暴涨
    B       +0.1     +1%       差不多随机
    C        0.0     −2%       差不多随机
    D       −0.1     +2%       差不多随机
    E       −3.0     −18%      因子极小，也暴跌

# Pearson 看数值直线；Spearman 看名次同向

Pearson：因子和收益当平面上的点，看能不能用一条直线概括。
点离原点越远、越贴那条线，ρ 越大。A=+3 且暴涨、E=−3 且暴跌，两个远点几乎单独决定斜率。

Spearman：先各自变成名次，再对名次做 Pearson。
只问「因子更大的，收益是不是也更靠前」，不问大了多少。
A 是 +3.0 还是 +0.5，只要仍是当天最大，名次都是 5。
单调变换（取 log、换单位、尾巴拉长）几乎不动 Spearman，会大幅改 Pearson。

同一 5 只加上名次：

    股票  因子   下期收益  因子名次  收益名次
    A    +3.0   +20%     5        5
    B    +0.1   +1%      4        3
    C     0.0   −2%      3        2
    D    −0.1   +2%      2        4
    E    −3.0   −18%     1        1

    5 只一起：          Pearson 0.99，Spearman 0.70
    去掉 A、E（B/C/D）：Pearson −0.24，Spearman −0.50
    次序不变、A/E 收到 ±0.5：Pearson 仍约 0.97，Spearman 还是 0.70

Spearman 把 0.99 打回 0.70，因为中间名次对不上（B/C/D 是 4-3、3-2、2-4）。
它仍是正的 0.70：A 最高对最高、E 最低对最低，两头名次对齐就够抬秩相关。
「没被拽歪」只抗「数值特别大」这一种；「只有两只极端票的排序是对的」Spearman 照样中招，幅度小一些。

    情况                      Pearson     Spearman      分层组均值
    一两只数值特别猛          易炸        稳住          稳住
    只有两头名次对、中间乱    仍可能很高  仍可能中等偏高  中间组会露馅
    真单调 Q5>…>Q1            通常也高    高            高且能看见台阶
    U 形 / 两头尖             可能接近 0  可能接近 0    两头高、中间塌

仓库主路径用 Spearman，是不当「暴涨暴跌那两只」的数值奴隶，
不是为了证明「因子大的一组都在赚」。后一句要看 Q1…Q5 组平均，
或至少看去掉两头之后中间还在不在。
Spearman = 抗幅度离群，不抗「只有两头在说话」。
分层不是 Spearman 的替代相关，是在问另一件事。

# 为什么打印 Q5−Q1（减一下有什么用）

Q5−Q1 = 做多因子最大组、做空因子最小组，这一笔多空的收益。
五组都是下期平均收益。牛市里五组可能都是正的，只看 Q5 像因子有用，其实大盘在抬所有人。
减去 Q1：两边一起涨时差里对冲掉一截大盘，剩下「因子大的比因子小的多赚多少」。
市值中性的多空组合，赚的就是这截价差。还要看 Q2/Q3/Q4 是否台阶上去；
只有两头差大、中间乱，仍可能是极端票。

# 场景
单因子评估、多空组合构建。评估仍要滞后、扣费；本文件只演示截面分层。

# 本文件
5 天 × 20 只股票。因子和「下一期收益」埋了同期斜率（表上的 fwd 已是 t+1）。
每天切五分位，再对天平均。
"""

import numpy as np
import pandas as pd

rng = np.random.default_rng(10)
days, n = 5, 20
factor = pd.DataFrame(rng.normal(size=(days, n)))
# 下期收益 ≈ 0.05×今天因子 + 噪声。表上的 fwd 已经是 t+1，和因子同行对齐。
fwd = factor * 0.05 + rng.normal(scale=0.08, size=factor.shape)
fwd = pd.DataFrame(fwd, index=factor.index, columns=factor.columns)

# 每天按因子五分位，看各组 fwd 均值。qcut 标签 1…5。
rows = []
for t in factor.index:
    q = pd.qcut(factor.loc[t], 5, labels=[1, 2, 3, 4, 5])
    mu = fwd.loc[t].groupby(q, observed=False).mean()
    rows.append(mu)
qmean = pd.DataFrame(rows).mean()
print("五组平均下期收益（1=因子最小 … 5=最大）\n", qmean)
# 多空价差：做多最高组、做空最低组，尽量去掉大盘水平。
print("多空 Q5-Q1", float(qmean.loc[5] - qmean.loc[1]))
print("口条：分层收益要单调；只报 IC 不够。")
