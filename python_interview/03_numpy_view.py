"""必考：NumPy 切片常是 view；pandas 加法按 index 对齐。

运行：python 03_numpy_view.py

# 人话
view = 换个窗口看同一块内存，改窗口等于改原数组。
copy = 另开一份，互不影响。
pandas 加减按行的名字（标签）对齐，不按「第 1 行加第 1 行」。

# 目的
取最近 20 日再原地改，会把整段历史一起改掉；两列日期对不齐时硬加会错行。

# 场景
`ret[-20:]` 做滚动窗口（只读或先 .copy()）。
两只股票收益相加、但停牌日不同 → 必须按日期对齐，不能 to_numpy() 按位置加。

# 什么是 view

ndarray 不是「一块数」这么简单，而是：
    对象头（shape / dtype / strides / 指向数据的指针）
  + 数据区（连续或带步长的 C 数组）

view = 新对象头，指针仍指同一块数据区。
想成 C++ 的 span / string_view：换了一个窗口，内存还是那份。
copy = 新对象头 + 新数据区。写 copy 不影响原来的数组。

a[:2] 这种基本切片（连续一段、或固定步长）几乎总是 view。
a[[0, 1]] 这种花式下标、以及 a[a > 0] 布尔下标，一般是 copy。
要自己保证独立：b = a[:2].copy()。

# 切片语法 a[start:stop:step]（Python 列表、NumPy 一样）

半开区间 [start, stop)：含头不含尾。和 C++ 的 begin/end、Rust 的 .. 一样。
省略 start = 从头；省略 stop = 到尾；省略 step = 1。

    a[:2]      下标 0、1          前两个
    a[1:3]     下标 1、2          不含 3
    a[::2]     0、2               隔一个
    a[-20:]    最后 20 个（不够就全要）

这里的 a 是 np.arange(4)，shape==(4,)，一维向量，不是表。
没有行、也没有列，只有轴 0 上的 4 个槽位：

    下标  0   1   2   3
    值    0   1   2   3

所以 a[:2] 是切前两个元素，不是「切列」。
你把它想成一列 4 行也对：切的是前两行。但内存布局是 1D，
打印出来是 [0 1 2 3] 横着一排，不是 4×1 的矩阵。

真要行列，得是二维，逗号隔开「行 , 列」：

    m = np.arange(12).reshape(3, 4)   # 3 行 4 列
    m[:2]        前 2 行，所有列      省略的轴 = 全要
    m[:, :2]     所有行，前 2 列
    m[:2, 1:3]   前 2 行，列 1、2

pandas 同理：df[:2] 前两行；df.iloc[:, :2] 前两列。
DataFrame 是列式存的，但切片记号仍是 [行, 列]，行在前。

# 本文件上半：改 view 等于改原数组

a = [0, 1, 2, 3]
b = a[:2]          # 一维：前两个槽位。窗口盖住 a[0], a[1]
b[0] = 99          # 写的是 a 的第 0 格
于是 a 变成 [99, 1, 2, 3]

回测里：ret_win = ret[-20:] 再原地改 ret_win，整段历史收益也被改。
窗口只读、或改完还要留着原序列，先 .copy()。

# 默认 index 是什么

不写 index= 时，pandas 给 RangeIndex：0, 1, 2, …。
这是贴在每行上的整数**标签**，不是 C 数组下标。
没删行、没改名时，标签碰巧等于位置，s1+s2 看起来像按槽位加。
本文件显式写了 ["a","b"] / ["b","c"]，一对不齐才露出「按名字加」。

取数：.loc 按标签，.iloc 按位置（第几行）。详见 02_pandas_loc.py。

# 本文件下半：pandas + 按标签，不是按位置

s1.index = a, b
s2.index = b, c
s1 + s2 只在两边都有的标签上相加（这里是 b: 2+10）。
只有一边有的标签填 NaN（a、c）。
s1.to_numpy() + s2.to_numpy() 丢掉标签，按槽位相加：1+10、2+20。

口条：NumPy 切片默认共用内存；pandas 加减默认对标签。
"""

import numpy as np
import pandas as pd

# 0, 1, 2, 3 连续一块 int。a 是对象头，数据区四个整数。
a = np.arange(4)

# a[:2] = a[0:2:1]：轴 0 上取 [0, 2)，即 a[0]、a[1]。
# 一维没有「切行/切列」；若把 4 个数想成一列，就是前两行。
# 新对象头 b，指针仍指 a 的数据区。b.shape==(2,)。
b = a[:2]

# 写 view 的第 0 格 = 写 a 的第 0 格。a 变成 [99, 1, 2, 3]。
# 若先 b = a[:2].copy()，这里只会改副本，a 仍是 [0, 1, 2, 3]。
b[0] = 99

# 验证：打印 a 就能看见 99。b.base is a 为 True（b 的数据来自 a）。
print("改 b 之后 a =", a, "  # a[0] 一起变了")

# 两列收益想加：标签不同。s1 有 a、b；s2 有 b、c。值按标签挂着。
s1 = pd.Series([1.0, 2.0], index=["a", "b"])
s2 = pd.Series([10.0, 20.0], index=["b", "c"])

# 标签对齐：a 只有左边 → NaN；b 两边都有 → 2+10=12；c 只有右边 → NaN。
# 不是「第一项加第一项」。
print("按标签相加\n", s1 + s2)

# 剥掉 index，剩下两个长度为 2 的 ndarray，按位置加：1+10、2+20。
print("按位置相加", s1.to_numpy() + s2.to_numpy())
