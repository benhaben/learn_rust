"""进阶：平稳特征；朴素标签 = 下一根收益。

运行：python 09_features_label.py

# 人话
特征 X = 今天收盘时已经知道的数（收益、波动、标准化收益）。
标签 y = 要预测的东西，这里是「下一根收益」。
收盘价本身不平稳（100 和 200 只是水平不同），树会偷学价位，换一段行情就垮。

# 目的
X 要可重复（平稳、不泄漏）；y 要对齐还没发生的收益。特征列绝不能 shift(-1)。

# 场景
造因子表、训线性/树。还想保留一点价格水平时，用分数差分（16），不要直接丢 close。
真正下单还要再晚一根（13）。

# 为什么特征要用收益 / 波动，不要收盘价

价格是随机游走，100 和 200 只是水平不同，没有平稳分布。
树模型会偷学「价位高就怎样」，样本外换一段行情就垮。
收益已经差分，波动是滚动尺度，r/vol 是「今天动了几倍波动」——这些更像可重复的模式。

# 标签为什么是下一根，还要再晚成交

y = r1.shift(-1)：第 t 行的标签是 t+1 的收益。
特征停在 t（今天收盘算完的 r、vol、z），预测的是「下一根涨多少」。
真正下单至少还要再晚（信号 t，成交 t+1 开/VWAP，见 13）。
shift(-1) 把未来填进今天，只当标签；特征列绝不能 shift(-1)。

# 为什么用假价格，以及这一行怎么造

练的是特征怎么造，不是预测某只真股票：不用下载、种子可复现。
真行情带着趋势和跳空，容易以为模型学到了东西。
对一条没有 alpha 的随机游走，仍然该用收益/波动，不该把收盘价丢进树。
不用 linspace 斜线：没有波动，vol20、z 没意义。

    normal(0, 0.01, 60)   抽 60 个日对数收益 r（正态，不是价钱）
    cumsum                连加 → log(Pt/P起点)，log 价格路径
    exp                   e^{Σr} = Pt/P起点，回到财富倍数（和 04 同一套）
    ×100                  起点定在 100 块附近

第一根是 100*exp(r0)，r0 一般不是 0，开头在 100 左右晃，不是精确 100。

# 本文件

假价格 → 对数收益 r1 → 20 根波动 → z=r/vol → 标签=下一根 r1。
"""

import numpy as np
import pandas as pd

# 正态抽对数收益 → cumsum 叠成 log 价 → exp 回真价钱 → ×100。
# 种子 2，日波 1%。几何随机游走，价格恒正。
px = pd.Series(100 * np.exp(np.cumsum(np.random.default_rng(2).normal(0, 0.01, 60))))

# 空表，行对齐价格的日期（默认 0..59）。后面按列往里填特征。
feat = pd.DataFrame(index=px.index)

# 对数收益：log(今)-log(昨)。第 0 格 NaN。平稳特征，不是价格水平。
feat["r1"] = np.log(px).diff()

# 过去 20 根 r1 的样本标准差（滚动窗口）。前 19 根不够窗长，是 NaN。
# 今天的 vol 只用到今天及以前的收益，没有未来。
feat["vol20"] = feat["r1"].rolling(20).std()

# 标准化收益：今天收益 / 近 20 日波动。+2 表示「涨了约 2 倍近期 σ」。
# 牛市大波动和熊市小波动被拉到同一尺度，比裸 r1 好进模型。
feat["z"] = feat["r1"] / feat["vol20"]

# 标签 = 下一根的 r1。shift(-1) 往「更早」填（和 shift(1) 相反）：
# feat[t] 的 y 是 r1[t+1]。特征列仍停在 t，只有 y 看了未来 1 根。
y = feat["r1"].shift(-1)

# 最后几行：r1、vol20、z。最后一行 y 会是 NaN（没有下一根）。
print(feat.tail(3))
print("标签 y 比特征多看未来 1 根，成交至少再晚 1 根（见 13）。")
# 不要 feat["close"] = px 直接进树 —— 模型会学价格水平，样本外失效。
