"""必考：按时间切分；标准化只 fit 训练集。

运行：python 07_leakage_split.py

# 人话
泄漏 = 测试集（未来）的信息漏进了训练集。
常见两招：用全样本均值/标准差做标准化；sklearn 默认 shuffle=True 把后面的日子洗进训练。
正确：先按时间切开，μ、σ 只从训练折算，再套到测试折。

# 目的
样本外 AUC / Sharpe 不虚高。测试折标准化后均值不必是 0——那才是没偷看。

# 场景
任何机器学习切分、标准化、填缺失、主成分。金融行是时间，不能当图片那样打乱。

# 这个例子在说明什么

不是在报「模型准不准」，而是演示标准化的正确姿势：
    mu、sd 只能从训练集算，再拿去套测试集。
测试集标准化后均值不必是 0——那不是 bug，是「没偷看未来」。

若先对全部 100 行算 mu/sd 再切，或 sklearn 默认 shuffle=True
把后面的大数洗进训练集，测试信息漏进 mu，回测 AUC 会虚高。

shuffle = 洗牌：打乱行序再切。图像里每张图独立，可以洗。
金融行是时间：第 80 天是未来。洗完未来会进训练集，等于偷看。
本文件用 iloc[:70] / iloc[70:]，不洗牌，先过去、后未来。

# 为什么训练折打印 -5e-16、测试折打印 2.47

-5e-16 = -0.0000000000000005，就是 0，浮点加减的渣。
标准化 (x-μ)/σ 之后，**被用来算 μ 的那批数**均值一定回到 0。

z 是假列名：linspace(0,1,100) 从 0 均匀走到 1，时间越往后越大。
前 70 行（训）大约 0～0.70，后 30 行（测）大约 0.71～1，整体更大。
测的数用训的 μ/σ 去套，会落在「比训练集平均高约 2.5 个标准差」，
所以测试折均值是 2.47，不是 0。

口条：先按时间切，再只 fit 过去。测试折均值不是 0 才对。
"""

import numpy as np
import pandas as pd

n = 100
# z = 假特征名。100 个点从 0 升到 1，模拟「随时间变大」的因子。
X = pd.DataFrame({"z": np.linspace(0, 1, n)})

# 前 70% 训练、后 30% 测试。iloc 按位置切，时间顺序不打乱。
cut = int(n * 0.7)
X_tr, X_te = X.iloc[:cut], X.iloc[cut:]

# 只看训练集的均值、标准差。ddof=0：这 70 个数当总体，分母 /n。
mu, sd = X_tr.mean(), X_tr.std(ddof=0)

# 两边都用训练折的 mu/sd。禁止用 X.mean()（全样本，含未来）。
X_tr_s = (X_tr - mu) / sd
X_te_s = (X_te - mu) / sd

# ~0 是浮点渣；2.47 是测试段整体更大，用了过去的尺子。
print("训练折均值应接近 0（-5e-16 就是 0）", float(X_tr_s.mean().iloc[0]))
print("测试折用训练折 mu/sd，均值不必是 0", float(X_te_s.mean().iloc[0]))
# shuffle=True 是 sklearn 默认。金融必须 False，或自己按时间 iloc 切。
print("禁止：sklearn 默认 shuffle=True 的随机切分。")
