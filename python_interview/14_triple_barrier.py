"""进阶：三重屏障标签 = 先碰到止盈 / 止损 / 超时。

运行：python 14_triple_barrier.py

# 人话
不预测「明天涨多少」，而问：这笔交易先碰到止盈、止损，还是时间到了。
上边 = 涨到入场×(1+止盈) → 标签 +1；下边 = 跌到入场×(1−止损) → −1；
走满 N 根还没撞 → 0（超时）。盒子宽度按入场当时的波动缩放。

# 目的
标签更接近真实交易规则。利润在尾部：准确率 55% 仍可能亏（对了很多小波动，错了几次大止损）。

# 场景
趋势/突破策略打分类标签，再接 meta-labeling（18）。
路径只用来打 y，不进 X。每天都当事件则窗口重叠，切分要 purge（08、22）。

# 三个边

上屏障：价格涨到 入场 × (1+pt) → 标签 +1（止盈）
下屏障：跌到 入场 × (1-sl) → 标签 -1（止损）
垂直屏障：走满 max_h 根还没碰到 → 标签 0 或按到期收益符号

pt、sl 要随当时波动缩放（本文件 1.5×近 vol_win 日 σ），否则牛市全是上障。

# 和「下一根收益」差在哪

09 的 y=r.shift(-1) 是回归明天涨多少。
三重屏障是分类：这段持有里先碰到谁。利润在尾部，准确率 55% 仍可能亏
（对了很多小波动，错了几次大止损）。评估看扣费后的钱，不看 accuracy。

# 后面训练用不用这段路径？

只用路径来**打 y**，不把路径当 X。
  X = 入场当时及以前的特征（收益、波动、因子…），停在 t
  y = 这段未来先撞哪条边（+1 / -1 / 0）
模型学的是「现在这种状态下，这笔交易更像止盈还是止损」，
不是序列模型去拟合整段未来价格。未来价格若进特征，就是泄漏。
每天都当事件，标签窗口重叠——这就是 08 要 purge 的原因。实盘事件应稀疏。
接上切分和扣费评估：22_purge_net.py（仍是假行情，换真 px 即可）。
"""

import numpy as np
import pandas as pd

# 固定种子，每次跑出同一条假行情，方便对口条。
rng = np.random.default_rng(5)

# 造 80 天收盘价，和 09 同一套：
#   1) 抽 80 个日对数收益 ~ N(0, 1%)
#   2) cumsum 得到对数价格路径
#   3) exp 还原成正价格，起点 100
# 这是没有 alpha 的随机游走，只用来演示怎么打标签。
px = pd.Series(100 * np.exp(np.cumsum(rng.normal(0, 0.01, 80))))

# 滚动波动窗口。改这里即可，循环起点会跟着走。
vol_win = 20

# 近 vol_win 日波动：先变回对数收益，再滚动标准差。
# diff() 第 0 格是 NaN；rolling 默认要凑满 vol_win 个非空收益，
# 所以 vol 从下标 vol_win 才有数（窗口正好是收益 1 … vol_win）。
# 前面都是 NaN，不能入场，否则 pt/sl 是 NaN，上下沿比较全失败、假超时。
# 屏障宽度必须用「入场当时已经知道的」vol，不能用未来那段 path 的 vol。
vol = np.log(px).diff().rolling(vol_win).std()

# pt=止盈宽度，sl=止损宽度，都是相对入场价的比例。
# 1.5×σ：波动大盒子大，避免牛市固定 ±1% 时标签全是 +1。
# 日波动很小时，对数 σ 和简单收益 (P1/P0-1) 几乎一样，面试够用。
pt = sl = 1.5 * vol

# 垂直屏障：最多再拿 10 根。还没撞上下沿就超时，标签记 0。
max_h = 10

# 每个元素以后是 (入场下标 t, 标签, 持有了几根才撞上)
labels = []

# 每个 t 开一个「虚拟仓」。演示才天天开；实盘应稀疏（信号触发才开）。
# 起点 vol_win：第一个 vol 非空的下标，和 rolling(vol_win) 对齐。
# 上界 len-max_h：保证后面一定还有 max_h 根可扫，不会越界。
for t in range(vol_win, len(px) - max_h):
    # 入场价。演示按「t 当天收盘进」。更严应对齐 13：特征停在 t，成交用 t+1。
    p0 = px.iloc[t]

    # 入场瞬间把盒子钉死。后面几天波动变了，上下沿也不改。
    # up / dn 只用 pt[t]、sl[t]，没有用到 t 之后的信息。
    up, dn = p0 * (1 + pt.iloc[t]), p0 * (1 - sl.iloc[t])

    # 入场之后的最多 10 根收盘（不含当天）。这是「未来路径」，只用来打 y。
    # 切片是半开区间 [t+1, t+1+max_h)，长度正好 max_h。
    path = px.iloc[t + 1 : t + 1 + max_h]

    # 先假定超时：走满 10 根还没撞，lab=0，hit=10。
    # 内层一撞到就改掉 lab/hit 并 break。
    lab, hit = 0, max_h

    # i=入场后第几根（1..10），p=那根收盘价。按时间从近到远扫，先碰到谁算谁。
    for i, p in enumerate(path, start=1):
        if p >= up:
            lab, hit = 1, i  # 先碰到上沿 → 止盈
            break
        if p <= dn:
            lab, hit = -1, i  # 先碰到下沿 → 止损
            break
        # 同一根收盘同时穿两边（大跳空）时，本文件先判上沿，算 +1。
        # 实盘要用盘中 high/low 或明确的「先高后低」规则，不能只看收盘。

    # 这一仓结束。相邻 t 的 path 几乎重叠，所以相邻标签会高度相关。
    labels.append((t, lab, hit))

# 列：t=哪天开的仓；label∈{+1,-1,0}；bars_to_hit=拿了几根（超时就是 max_h）
s = pd.DataFrame(labels, columns=["t", "label", "bars_to_hit"])

# 三类是否极端失衡。随机游走 + 这段样本路径，经常一边特别多，属正常。
print("标签计数\n", s["label"].value_counts().sort_index())
print("前 8 个事件（1=先止盈 -1=先止损 0=超时）\n", s.head(8))
print("口条：三个边=止盈/止损/超时；屏障按波动缩放。路径只打 y，不进 X。")
