"""进阶：分数差分 — 要平稳，又比一阶差分少丢价格记忆。

运行：python 16_frac_diff.py

# 人话：差分就是「差」，今天减昨天

是的。时间序列里的「差分」就是相邻两期相减，不是别的高级运算：
    一阶差分  ΔP_t = P_t − P_{t−1}
价格 100 → 102 → 101，差分就是 +2、−1。
对数上一阶差分 = ln P_t − ln P_{t−1}，就是对数收益（见 04）。

为什么要减？价格会慢慢爬（不平稳：均值跟着走，100 可以爬到 200）。
减完只剩「变动」，分布更稳，模型才好学。
和小学减法是同一件事，只是对一整条序列逐期做。

二阶差分 = 对差分再减一次（变动的变动），很少直接当收益。
分数差分 = 不只要「今天减昨天」，而是：
    今天 − （昨天×较大权重 + 前天×小一点 + 更早×更小 + …）
权重按公式算，越远越小，这就是「慢慢衰减」。d 是小数（0 到 1）。

# 目的：权重为什么慢慢衰减、不一下子变成 0

d=1：权重 [1, −1, 0, 0, …] → 只减昨天，更早的全部扔掉。
      最平稳，但 100 块和 200 块算出来可以一样，「价格在哪一带」没了。

d=0：权重只有 [1] → 原价原样留下，记忆全在，但不平稳。

d=0.4：权重 [1, −0.4, −0.12, −0.064, …] → 昨天减得多，更早还留一丁点。
      趋势被压住（更平稳），水平记忆没砍光。

衰减的目的：近的更有用（权重大），远的别一刀切（权重仍 > 0）。
这不是买卖信号，是「把价格变成更适合进模型的数」的预处理。

# 场景：什么时候用、什么时候不用

要用「带一点价格水平」的特征，又不能直接丢原始收盘价时：
    - 树/线性的输入：生价格不平稳，换一段行情均值变了就垮（见 09）
    - 只用收益率：太平稳，估值偏离、通道位置、离历史高点多远没了
    - AFML：对价格做分数差分（选能过平稳检验、又尽量小的 d），再当 X

生 close 为啥垮：训练段在 100 附近，树学到 close>110 就空；两年后在 200，
永远大于 110，会天天空。模型记住的是「100 这个数字」，不是「相对贵不贵」。
估值偏离、通道位置=(价−低)/(高−低)、离高点百分比、滚动 z、截面 rank
都是相对化之后的水平，100 和 200 仍同分布。能做成这些时，往往比分数差分更好解释。
z = (x−μ)/σ 去掉均值和尺度；rank 只留名次。都是归一，和「不要生 close」同一类。

不要用的时候：
    - 回测净值、组合加权 → 用简单收益（04），不是分数差分
    - 只关心涨跌、不要水平 → 普通一阶差分 / 收益率就够
    - 配对交易的价差 → 先看协整（20），不是先分数差分

本文件不跑 ADF。只打印 d=1 / d=0.4 的权重，再对假价格卷积，看还留不留水平。

# 这不是反向传播，也不是深度学习

容易混：两边都有「权重慢慢变小」。不是同一件事。

    分数差分     时间序列预处理：把价格变成更平稳、又留一点记忆的特征
    梯度下降     训练神经网络：沿损失函数对参数求导，一步步改权重
    反向传播     算那些梯度的算法（从输出层往输入层传）
    梯度消失     深层网络里梯度一层层乘，越传越小，前面层学不动

分数差分的 w_k 是公式算死的（给定 d 就固定），不训练、不求导、没有 loss。
后面接的通常是线性 / 树（09），不是 LSTM。深度学习在 `dl/`，和本文件无关。

# 权重公式从哪来（AFML / Hosking）

分数差分算子：(1−L)^d，L 是滞后：L P_t = P_{t−1}。
二项展开：
    (1−L)^d = Σ_k  C(d,k) (−L)^k
写成对过去价格加权：
    FD_t = w0 P_t + w1 P_{t−1} + w2 P_{t−2} + …

递推（不用每次算组合数）：
    w0 = 1
    w_k = −w_{k−1} · (d − k + 1) / k     k = 1, 2, 3, …

手算核对 d=1（应退化成普通差分 [1, −1, 0, 0, …]）：
    k=1: w1 = −1 · (1−1+1)/1 = −1
    k=2: w2 = −(−1) · (1−2+1)/2 = 0
    后面全是 0。于是 FD_t = P_t − P_{t−1}。

手算核对 d=0.4 前几项：
    w0 = 1
    k=1: w1 = −1 · (0.4−1+1)/1 = −0.4
    k=2: w2 = −(−0.4) · (0.4−2+1)/2 = −0.12
    k=3: w3 = −(−0.12) · (0.4−3+1)/3 = −0.064
    后面继续慢慢变小，不会突然变 0。旧价格还留一点。

选 d 的口条：小到序列能过平稳检验，又尽量靠近 0（多留记忆）。
实盘还要用过去样本估 d，不能拿全样本 ADF 调完再回测。

# 这里的卷积不是 CNN，也不是在说「卷积=矩阵乘法」

np.convolve 是信号处理的一维卷积：拿一串固定权重，从左滑到右，每一步做一次加权和。
和「20 日均线」是同一类操作，只是均线权重全是 1/20，这里权重是分数差分的 w。

    价格  P0 P1 P2 P3 P4 …
    权重  w0 w1 w2          （本文件 L=20，这里用 3 项示意）

    某一天 t=2：FD = w0*P2 + w1*P1 + w2*P0
    下一天 t=3：FD = w0*P3 + w1*P2 + w2*P1
    窗口右移一格，权重不变。这就是「同一核反复滑」。

一维卷积 = 滑窗加权和（均线是权重全 1/N 的特例）。
np.convolve 是 NumPy 函数，不是 Python 内置；定义会先把核翻转再滑，
翻转后恰好对上「w0 乘今天、w1 乘昨天」。不是 CNN，也不等于一般矩阵乘法。

数字：P=[10,20,30,40,50]，w=[1, −0.4, −0.12]
    窗 10,20,30 → 1*30 + (−0.4)*20 + (−0.12)*10 = 20.8
    窗 20,30,40 → 1*40 + (−0.4)*30 + (−0.12)*20 = 25.6
    窗 30,40,50 → 1*50 + (−0.4)*40 + (−0.12)*30 = 30.4
写成一次矩阵×向量（每行是上一行窗口右移一格 = 托普利兹 Toeplitz）：
    [[30,20,10], [40,30,20], [50,40,30]] @ [1, −0.4, −0.12] = [20.8, 25.6, 30.4]
matmul = 矩阵乘法。托普利兹 matmul 是这种错位矩阵去乘权重，数值上等于这次卷积。
一般的 A @ B 没有「同一核滑过去」的结构。

mode="valid" 只保留核完全盖住价格的位置，输出比价格短 L−1 格。
前 L−1 根没有足够历史，本来就算不了。手写循环也能算，convolve 只是少写 for。

和容易混的两件事：
    卷积神经网络 CNN  也是滑窗加权，但权重是训练出来的，而且常在二维图像上。
                      本文件权重由 d 算死，没有层、没有梯度。
    矩阵乘法          见上面的托普利兹；概念上记住滑窗加权和就够。
"""

import numpy as np  # 权重、假价格、卷积都用 NumPy
import pandas as pd  # 本文件没用到，和其他脚本统一留着，面试时不必纠结


def frac_weights(d, size):
    # d：差分阶。size：要几项权重。w[k] 乘的是 P_{t−k}。
    w = [1.0]  # w0=1，永远先乘「今天自己」
    for k in range(1, size):  # k=1,2,…,size-1，一项项往后续
        w.append(-w[-1] * (d - k + 1) / k)  # AFML 递推：下一项由上一项算出
    return np.array(w)  # 转成 ndarray，后面才能 convolve / round


w1 = frac_weights(1.0, 8)  # d=1，取前 8 项：应看到 [1, -1, 0, 0, …]
w04 = frac_weights(0.4, 8)  # d=0.4，取前 8 项：应看到慢慢衰减，不会突然变 0
print("d=1 权重（普通差分）", np.round(w1, 3))  # 四舍五入到 3 位，方便对口条
print("d=0.4 权重（慢慢衰减）", np.round(w04, 3))  # 对照：旧价格还有非零权重

rng = np.random.default_rng(7)  # 固定种子，每次同一条假价格
# 带正漂移的对数收益：均值 0.001、日波 1%，80 天。cumsum 叠成 log 价路径。
logp = np.cumsum(rng.normal(0.001, 0.01, 80))
px = 100 * np.exp(logp)  # exp 回正价格，起点约 100；有漂移，水平会往上爬
w = frac_weights(0.4, 20)  # 卷积用 20 项：今天 + 过去 19 根
# mode="valid"：只在权重核完全盖住价格时出数。输出长度 = 80-20+1=61。
# 第 1 个 FD 对应原序列下标 19（用了 px[0]…px[19]）。
# 一维滑窗加权，不是 CNN 层。等价于对每个 t 算 sum_k w[k]*px[t-k]。
fd = np.convolve(px, w, mode="valid")
print("价格首尾", float(px[19]), float(px[-1]))  # 和 fd 对齐的那段：第 20 根 vs 最后一根
print("分数差分首尾", float(fd[0]), float(fd[-1]), "（比价格短，水平被压住但仍相关）")
print("一阶差分均值", float(np.diff(px).mean()), "已经几乎不带水平")  # P_t−P_{t−1}，均值≈漂移，没有价位
print("口条：d=1 全丢记忆；d∈(0,1) 折中平稳和记忆。")  # 面试收尾一句
