"""必考：年化乘 sqrt(252)；Sharpe / Sortino / 最大回撤。

运行：python 05_vol_sharpe.py

# 为什么是根号 252，不是乘 252

假设每天收益独立、方差差不多（口条假设，现实常不成立）：
    一年的方差 = 252 × 一天的方差
标准差是方差开根：
    σ_年 = σ_日 × √252
日波动 1% → 年化约 1% × 15.87 ≈ 15.9%。
乘 252 会把波动变成 252%，那是在年化「期望收益」时才用：
    μ_年 ≈ μ_日 × 252
均值可加；标准差跟着方差走，所以开根。

A 股/美股常写 252 个交易日；加密常写 365。报告里写清。
隔夜跳空、重叠窗口会让「独立」假，√T 只是默认口径。

# Sharpe / Sortino / MDD

Sharpe = 超额收益的均值 / 超额收益的波动，再乘 √252 年化。
超额 = 比「躺着吃无风险」多赚的那截：策略日收益 − 日无风险。
年化 2% 必须先 /252 摊成日利率，不能写 r - 0.02（日收益和年利率量纲不同）。
分母用波动：同样多赚，抖得越厉害分数越低。

Sortino 只罚亏的那边：分母改成下行波动。
本文件用 clip(upper=0) 再 std：涨的日子变成 0 也进分母，是简化写法。
更严的 Sortino 用 √mean(min(ex,0)²)，只看亏的平方，不含涨日的 0。

MDD = 净值相对历史最高点的最大跌幅（最负的那个）。
路径依赖：同样年化，先暴涨再腰斩和慢慢爬，MDD 不同。

# 本文件在做什么

造一年假日收益（均值 3bp、波动 1%）→ 年化波动、Sharpe、Sortino、MDD。
给人看的是年化百分比和倍数；中间用日收益算，再乘 √252。
"""

import numpy as np
import pandas as pd

# 固定种子的随机数发生器，每次跑同一串数，方便对答案。
rng = np.random.default_rng(0)

# 252 个「日收益」：正态，均值 0.0003（约 3 个 bp），标准差 0.01（日波 1%）。
# 这是假数据，不是真行情。pd.Series 方便后面 .std / .mean / 对齐。
r = pd.Series(rng.normal(0.0003, 0.01, 252))

# 年化无风险 2% → 摊到每个交易日。超额收益要用日对日减，不能减 0.02。
rf_daily = 0.02 / 252

# ddof=1：样本标准差，分母 n-1（估总体时少偏一点）。ddof=0 是总体 /n。
# 先得日波动，再 ×√252 年化。面试默写这一行。
sig_y = r.std(ddof=1) * np.sqrt(252)

# 每天的超额：策略日收益减去当天那份无风险。后面均值、波动都用它。
ex = r - rf_daily

# Sharpe：日超额均值 / 日超额波动 ×√252。
# 均值已经是「每天平均多赚多少」，乘 √252 和波动同一套年化口径。
sharpe = ex.mean() / ex.std(ddof=1) * np.sqrt(252)

# 涨的超额改成 0，亏的保留。down 里有一串 ≤0 的数。
down = ex.clip(upper=0)

# Sortino：分子还是超额均值，分母换成下行波动，同样 ×√252。
# 只靠向上波动赚钱时，Sortino 会比 Sharpe 好看。
sortino = ex.mean() / down.std(ddof=1) * np.sqrt(252)

# 日收益连乘滚净值。这里 r 当简单收益用（假数据很小，和对数差不多）。
nav = (1 + r).cumprod()

# cummax = 到这一天为止净值的历史最高。
# nav/峰值 - 1 = 相对峰值跌了多少（没破新高就是负数或 0）。
# .min() 取出最惨的那一跌，就是最大回撤。
mdd = (nav / nav.cummax() - 1).min()

# :.2% 把 0.16 印成 16.00%；Sharpe 是倍数不是百分比。
print(f"年化波动 {sig_y:.2%}")
print(f"Sharpe {sharpe:.2f}  Sortino {sortino:.2f}  MDD {mdd:.2%}")
