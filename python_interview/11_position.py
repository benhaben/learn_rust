"""进阶：信号除以波动再归一，再缩放到目标波动。

运行：python 11_position.py

# 人话
信号是「谁多谁空、谁强谁弱」的分数，不是手数。
落地四步：信号÷各自波动 → |权重|加总归一成 1 → 昨仓×今收益 → 再乘杠杆，让组合年化波动对上目标（如 10%）。

# 目的
高波的少下，风险不被一只票吃掉；换股、换期货也能把产品对到同一目标波动。

# 场景
多标的配仓、波动目标产品、期货换合约。面试：波动目标 10%，怎么从预测落到手数？答这条。

# 这个例子在说明什么

信号不是仓位。A=+1、B=-0.5 只是「谁多谁空、谁强谁弱」，不能直接当手数。
常见落地：
    1) 信号 / 各自波动     高波的少下，风险不被一只票吃掉
    2) |权重| 加总归一成 1  杠杆不随信号乱漂
    3) 昨仓 × 今收益        和 10 一样，仓位必须滞后
    4) 再乘 scale           让组合年化波动对上目标（这里 10%）

面试：波动目标 10%，怎么从预测落到手数？答这条，不是「看涨就满仓」。

# 两处波动，两个系数

个股 rolling vol：决定相对比例（谁多谁少），总敞口仍是 1。
组合历史 vol：scale = 目标 / 实现年化波动，决定总杠杆。

标的换股、换期货、波动差一倍，只要用各自 vol 加权再按组合实现波动缩放，
都能把产品对到设计的目标波动（例如一直 10%）。这是波动目标产品的做法。
相关会变、危机里分散失效，实现波动仍可能偏离目标，要滚动重算 scale。
本文件 port_r.std() 用了整段样本，杠杆含一点未来；实盘只用到昨天的滚动/扩展波动。

# axis（第 43 行）

sum(axis=1)：横着加，每天一个 |A|+|B|。
div(..., axis=0)：这个数按日期对齐，当天 A、B 都除以当天那个分母。

# 本文件

假两只股票 → 固定信号 → 除波动 → 归一 → 组合收益 → 算出缩放系数。
scale 只打印，没有写回 w；实盘是 w *= scale。
"""

import numpy as np
import pandas as pd

# 种子 3，可复现。
rng = np.random.default_rng(3)

# 80 天 × 2 列日收益，均值 0、日波 1%。列名 A、B。
r = pd.DataFrame(rng.normal(0, 0.01, (80, 2)), columns=["A", "B"])

# 每天同一组信号：A 看多 1、B 看空 0.5。index 对齐 r，才能按行相除。
# 这是分数，不是仓位。
signal = pd.DataFrame({"A": 1.0, "B": -0.5}, index=r.index)

# 各列近 20 日波动。前 19 行 NaN。replace(0, nan) 避免后面除零。
vol = r.rolling(20).std().replace(0, np.nan)

# 逆波动：同样信号，B 若比 A 更抖，|raw_B| 更小。单位是「信号/波动」，还不是权重。
raw = signal / vol

# axis=1 横着加出每天一个分母；axis=0 按日期去除。|w_A|+|w_B|=1。
w = raw.div(raw.abs().sum(axis=1), axis=0)

# 昨权重 × 今收益，两列加总 = 当天组合收益。禁止 w * r（用了当天才有的仓）。
port_r = (w.shift(1) * r).sum(axis=1)

# 想要的组合年化波动 10%。
target_vol = 0.10

# 用组合历史实现波动反推总杠杆，对上产品目标 10%。换标的也走同一套。
# 整段 std 含未来；实盘应只用 t-1 及以前。ddof 默认 1。
scale = target_vol / (port_r.std() * np.sqrt(252))

print("未缩放组合年化波动", float(port_r.std() * np.sqrt(252)))
print("缩放系数", float(scale))
# 丢掉 vol 窗不够的 NaN 行，看归一后的 A/B 权重。
print(w.dropna().head())
