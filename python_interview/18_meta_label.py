"""进阶：meta-labeling — 主模型定方向，次模型决定下不下。

运行：python 18_meta_label.py

# 人话

AFML 的 meta-labeling：再训一个模型，专门预测「主模型这次的方向对不对」，
用来决定做不做、下多大。它不重新预测涨跌。

    1) 主模型（或规则）只出边：side = +1 / −1
    2) 三重屏障给这次下注打结果（见 14）。meta 标签只有 0/1：
         1 = 结果和主方向一致（做多且先止盈等）
         0 = 主方向错了，或超时没赚到
    3) 次模型用入场当时能知道的特征，预测 P(标签=1)
         低于阈值 → 空仓；过线 → 按下 P 定仓

# 「meta / 元」是什么意思

meta = 高一层、关于这件事本身（希腊语「在……之上」）。
中文「元」同一用法：元数据 = 关于数据的数据；元学习 = 学习怎么学。

    普通标签     标的是市场（明天涨、先碰到止盈）
    元标签       标的是主模型那一次对不对

所以 meta = 给「主模型的输出」再贴一张标签，判断的是判断。
不是两个模型平级投票看多空。

# 目的

主可以很笨、很稳，只负责方向；「何时下、下多大」交给次模型。
次模型可换一批特征（波动、点差、拥挤），不必再学一遍涨跌。
对了才交易 → 次数变少，精确率往往升，召回会掉（错过一些对的）。

主看 regime、次看置信度，和这套接近：regime 是玩法/方向，
置信度是跟不跟。AFML 原话是 side + 对错，没规定主必须是 HMM。
不是业界默认都上两个模型：一个 P(涨)+阈值、或硬规则过滤也很常见。

# 场景

已有趋势/套利边，要过滤没把握、拥挤、高成本时段。
屏障打完 +1/−1/0 后再预测会不会撞对的边。
本文件用「|昨收益| 大于中位数」当假次模型；真 meta 要另训分类器，
标签来自屏障对错。假数据上准确率不会升，只是次数少了。

# 本文件

主边 = 昨收益符号（动量）。对 = 今收益与昨仓同号。
对比「主信号每天都做」和「假 meta 过滤后再做」的次数与同向次数。
"""

import numpy as np
import pandas as pd

rng = np.random.default_rng(9)
r = pd.Series(rng.normal(0, 0.01, 200))
# 主边：昨涨则今做多（收盘后才有昨收益，乘今 r 不偷看）。
side = np.sign(r.shift(1))
correct = (side * r) > 0

# 次过滤：|昨收益| 大才做。演示用；真 meta 是用特征训一个分类器。
confident = r.shift(1).abs() > r.shift(1).abs().median()
trade = side.where(confident, 0.0)

n_all = int(side.fillna(0).ne(0).sum())
n_meta = int(trade.ne(0).sum())
hit_all = float(correct[side.ne(0)].mean())
hit_meta = float(((trade * r) > 0)[trade.ne(0)].mean())
print(f"主模型每天做：{n_all} 次，同向率 {hit_all:.2%}")
print(f"meta 过滤后：{n_meta} 次，同向率 {hit_meta:.2%}")
print("这份假数据过滤不抬准确率（过滤特征没信息），但次数少了。真 meta 要能预测「对不对」。")
print("口条：meta=关于判断的判断。主定+1/−1，次预测对不对，只决定下不下。")
