"""深度学习单独目录：短样本、表格特征，先线性/树，不要先 LSTM。

运行：python dl/02_why_not_first.py

# 面试怎么说

日频、股票截面、样本几年：有效独立点往往几千不到。
LSTM/Transformer 参数多，过拟合快，还难解释、难 PIT。
Jansen 后半本是工具箱，不是默认开工顺序。

先问：特征是否平稳、是否泄漏、扣费后有没有钱。
这些过了，再考虑序列模型（日内、限价单、另类文本）。

本文件不训练网络，只对比「可数的有效样本」和「一个小 LSTM 的参数量级」。
"""

n_days, n_names = 500, 50
# 粗算：每天一个截面，还要再除掉重叠标签，有效 n 远小于这个积。
print(f"日频面板大约 {n_days}×{n_names} = {n_days * n_names} 行")
print("标签重叠、同一行业一起动，有效独立样本再打一折")
# 隐状态 32、输入 8、一层：量级 10^3～10^4 参数，已经和有效 n 一个量级。
approx_lstm_params = 4 * (32 * 32 + 32 * 8 + 32)
print(f"很小的 LSTM 也有约 {approx_lstm_params} 个参数")
print("口条：短样本先线性/浅树。深度学习单独准备，不当默认。")
