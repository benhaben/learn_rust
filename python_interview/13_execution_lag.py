"""压轴：信号用 t 的信息，收益至少用下一根。

运行：python 13_execution_lag.py

# 人话
今天收盘才算出的信号，吃不到已经走完的当天涨跌。
能做的是：昨信号 × 今收益。shift(1) 是把信号对齐到「开盘时你已经知道的那个」，不是信号失效。

# 目的
回测不偷看。cheat = 今信号×今收益，收盘才知道却吃了全天涨。

# 场景
日频信号、收盘算因子次日开盘/VWAP 成交。盘中能算并能马上成交，滞后可以短于 1 根；
回测默认仍至少「这根 bar 吃不到」。成分/财报用 merge_asof 对齐可知时间。

# shift(1) 不是信号过期没用

信号往右挪一格，对齐的是可交易时间：用「已经知道的旧信号」赚「还没发生的新收益」。
今天收盘才算出的新信号，乘不上今天已经走完的 r。

    signal         1      1     -1      0
    shift(1)     NaN      1      1     -1
    去乘的 r             日1    日2    日3

日 1 的 ok 用日 0 收盘的 +1：相对日 1 的新信号是「旧了一天」，
但日 1 开盘时你只有日 0 的信号。日 1 新信号要等日 1 收盘才存在。

    cheat = 今信号 × 今收益   偷看，收盘才知道却吃了全天涨
    ok    = 昨信号 × 今收益   做得到（和 10 的昨仓 × 今收益同一件事）

盘中能算并能马上成交，滞后可以短于 1 根；回测默认仍至少「这根 bar 吃不到」。

# 本文件四天（信号收盘后才知道）

    日    r     signal   cheat        ok
    0   +1%     +1      +1% 偷看    NaN
    1   -2%     +1      -2%         昨+1 × (−2%)
    2  +1.5%    −1     −1.5%        昨+1 × 1.5%
    3    0       0       0          昨−1 × 0
"""

import pandas as pd

# 四天简单收益。
r = pd.Series([0.01, -0.02, 0.015, 0.00], name="r")

# 收盘后才知道的目标仓：多、多、空、平。不是开盘前就能用的。
signal = pd.Series([1, 1, -1, 0], name="signal")

# 同一根收盘算信号又乘这根收益 = 用未来信息。
cheat = signal * r

# 昨信号 × 今收益。旧一天 = 成交晚一天，不是失效。
ok = signal.shift(1) * r

print(pd.DataFrame({"r": r, "signal": signal, "cheat": cheat, "ok": ok}))
print("口条：信号 t，成交至少 t+1。PIT 成分/财报用 merge_asof。")
