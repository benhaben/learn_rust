"""绿皮后半：远期 vs 期货。每日盯市时，利率再随机，两者价格可以分家。

运行：python 27_fwd_fut.py

无股息远期：F = S e^{rT}（或离散复利）。这是**合约约定价**，进场零价值。
期货每天结算：盈亏立刻变成现金，能再投资。
利率确定（或与期货无关）⇒ 期货价 = 远期价。
利率与标的同向（股指）⇒ 期货通常略高于远期；反向则低。口条说到即可。

口条：定价公式先写远期。期货多一个「保证金利息」的协方差。
"""

import numpy as np

s, r, t = 100.0, 0.05, 0.75
f = s * np.exp(r * t)
print(f"F = S e^{{rT}} = {f:.4f}  （进场价值 0）")
print("到期赚的是 S_T − F，和期货累计盯市在「r 确定」时现值相同。")
print("口条：r 确定则远期=期货。r 随机且与 S 相关，才分家。")
